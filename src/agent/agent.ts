async function summarizeFailurePhase(task: Task, _homeDir: string, errors: string): Promise<string> {
    try {
        const { b } = await import('../infra/baml');
        const { redactText } = await import('../security/redactor');
        const result = await b.SummarizeFailure({
            validationOutput: await redactText(errors.substring(0, 2000)),
            attempt: task.attempt,
            maxAttempts: task.maxAttempts,
        });
        return result.summary;
    } catch {
        return "Task failed due to persistent validation errors.";
    }
}

function getValidationSummary(output: string): string[] {
    const summary: string[] = [];
    if (output.includes('Biome')) {
        summary.push(output.includes('✓') || output.includes('pass') ? '✅ Biome' : '⚠️ Biome');
    }
    if (output.includes('TSC') || output.includes('TypeScript')) {
        summary.push(output.includes('✓') || output.includes('0 error') ? '✅ TSC' : '⚠️ TSC');
    }
    if (output.includes('Ruff')) {
        summary.push(output.includes('✓') || output.includes('pass') ? '✅ Ruff' : '⚠️ Ruff');
    }
    if (output.includes('Mypy')) {
        summary.push(output.includes('✓') || output.includes('Success') ? '✅ Mypy' : '⚠️ Mypy');
    }
    if (output.includes('Trivy')) {
        summary.push(output.includes('✓') || output.includes('0 vulnerabilities') ? '✅ Trivy' : '⚠️ Trivy');
    }
    return summary;
}

async function generatePRDescription(
    workDir: string,
    git: any,
    taskDescription: string,
    validationResult: { success: boolean; output: string; languages?: string[] }
): Promise<string> {
    try {
        const diffStats = await git.diffSummary(['main']);
        const filesChanged = diffStats.files?.length || 0;
        const insertions = diffStats.insertions || 0;
        const deletions = diffStats.deletions || 0;

        const testFiles = diffStats.files?.filter((f: any) =>
            f.file?.match(/\.(test|spec)\.|tests\/|__tests__\//)
        ).length || 0;

        const validationSummary = getValidationSummary(validationResult.output);

        const sections: string[] = [];
        if (taskDescription?.trim()) {
            sections.push(`## Task Description\n\n${taskDescription.trim()}`);
        }

        sections.push(
            `## 📊 Changes Summary\n`,
            `- **Files changed:** ${filesChanged}`,
            `- **Insertions:** +${insertions}`,
            `- **Deletions:** -${deletions}`
        );

        if (testFiles > 0) {
            sections.push(`- **Test files:** ${testFiles} modified/added`);
        }

        if (validationSummary.length > 0) {
            sections.push(
                `\n## ✅ Validation\n`,
                validationSummary.join(' • ')
            );
        }

        sections.push(`\n---\n🤖 Generated by [Ralph Platform](https://github.com/Replikanti/ralph-platform)`);

        return sections.join('\n');
    } catch (error) {
        logger.warn({ err: error }, '⚠️ Failed to generate PR description');
        return taskDescription || 'Implementation completed by Ralph';
    }
}

async function createPullRequest(repoUrl: string, branchName: string, title: string, body: string): Promise<string | null> {
    const { owner, repo } = parseRepoUrl(repoUrl);
    try {
        const { Octokit } = await import("@octokit/rest");
        const octokit = new Octokit({ auth: process.env.GITHUB_TOKEN });
        
        const response = await octokit.rest.pulls.create({
            owner,
            repo,
            title,
            body,
            head: branchName,
            base: 'main', 
        });
        return response.data.html_url;
    } catch (e: any) {
        logger.error("PR failed: " + e.message);
        return null;
    }
}

