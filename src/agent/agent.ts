// --- TYPES ---

export interface Task {
    ticketId: string;
    title: string;
    description?: string;
    repoUrl: string;
    branchName: string;
    jobId: string;
    attempt: number;
    maxAttempts: number;
    mode?: 'full' | 'plan-only' | 'execute-only';
    existingPlan?: string;
    additionalFeedback?: string;
    isIteration?: boolean; // Flag indicating this is a PR iteration (fix request)
}


interface IterationContext {
    workDir: string;
    homeDir: string;
    task: Task;
    availableSkills: string;
    git: any;
    trace: any;
}

